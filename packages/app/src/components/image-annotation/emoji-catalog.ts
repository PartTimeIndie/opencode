export type EmojiEntry = { id: string; glyph: string; name: string; keywords: string; category: string }
export const emojiCatalog: EmojiEntry[] = groups.flatMap(([category, keywords, rows]) => rows.split("\n").map((row) => {
  const [glyph, en, de] = row.split("|")
  return { id: glyph, glyph, name: `${de} / ${en}`, keywords: `${keywords} ${de} ${en}`.toLocaleLowerCase(), category }
})).filter((entry, index, all) => all.findIndex((other) => other.id === entry.id) === index)

export type EmojiUsage = Record<string, { count: number; last: number }>
export function frequentEmojis(usage: EmojiUsage): EmojiEntry[] {
  const defaults = ["👉", "❌", "✅"]
  return [...emojiCatalog].sort((a, b) => (usage[b.id]?.count ?? 0) - (usage[a.id]?.count ?? 0) || (usage[b.id]?.last ?? 0) - (usage[a.id]?.last ?? 0) || (defaults.includes(a.id) ? defaults.indexOf(a.id) - 3 : emojiCatalog.indexOf(a)) - (defaults.includes(b.id) ? defaults.indexOf(b.id) - 3 : emojiCatalog.indexOf(b))).slice(0, 3)
}
export function searchEmojis(query: string, category = "") {
  const words = query.trim().toLocaleLowerCase().split(/\s+/)
  return emojiCatalog.filter((entry) => (!category || entry.category === category) && words.every((word) => entry.keywords.includes(word) || entry.glyph.includes(word)))
}
