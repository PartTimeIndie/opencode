import { describe, expect, it } from "bun:test"
import { ControlSurface } from "@opencode-ai/core/control-surface"

describe("ControlSurface", () => {
  it("validates form effects and marker actions", () => {
    expect(
      ControlSurface.validateFormDefinition({
        version: 1,
        fields: [
          { id: "preview", type: "video_preview", src: "clip.mp4" },
          { id: "cut_range", type: "duration_range", defaultValue: { start: 1, end: 2 } },
        ],
        effects: [{ id: "seek_preview", target: "ui.preview.media.currentTime", value: "${values.cut_range.start}" }],
        actions: [
          {
            id: "mark_start",
            trigger: { event: "markStart", source: "preview" },
            steps: [{ type: "setValue", target: "values.cut_range.start", value: "round(${state.preview.currentTime}, 2)" }],
          },
        ],
      }),
    ).toEqual([])
  })

  it("reports removed fields and unsafe expressions", () => {
    const diagnostics = ControlSurface.validateFormDefinition({
      version: 1,
      fields: [{ id: "preview", type: "video_preview", rangeField: "cut_range" }],
      effects: [{ id: "bad", target: "ui.preview.style.background", value: "eval(${values.preview})" }],
    })

    expect(diagnostics.map((diagnostic) => diagnostic.code)).toContain("SURFACE_REMOVED_FIELD")
    expect(diagnostics.map((diagnostic) => diagnostic.code)).toContain("SURFACE_UNSUPPORTED_TARGET")
    expect(diagnostics.map((diagnostic) => diagnostic.code)).toContain("SURFACE_UNSUPPORTED_FUNCTION")
  })

  it("evaluates only the supported template functions", () => {
    expect(ControlSurface.evaluateExpression("round(${state.preview.currentTime}, 2)", { values: {}, state: { preview: { currentTime: 12.345 } } })).toBe(12.35)
    expect(ControlSurface.evaluateExpression("translate(${values.x}, ${values.y})", { values: { x: 1, y: 2 } })).toBe("translate(1, 2)")
    expect(ControlSurface.evaluateExpression("${result.stdout}", { values: {}, result: { stdout: "preview.png" } })).toBe("preview.png")
    expect(ControlSurface.evaluateExpression("${result.json.includeWebGL}", { values: {}, result: { json: { includeWebGL: true } } })).toBe(true)
    expect(ControlSurface.evaluateExpression("Profile: ${result.json.profileName}", { values: {}, result: { json: { profileName: "PU" } } })).toBe("Profile: PU")
  })

  it("rejects legacy or empty authored display fields while preserving an explicit description", () => {
    expect(
      ControlSurface.validateFormDefinition({
        version: 1,
        fields: [{ id: "summary", type: "display", label: "Summary", defaultValue: "Legacy copy" }],
      }).map((diagnostic) => diagnostic.code),
    ).toEqual(["SURFACE_LEGACY_DISPLAY_CONTENT", "SURFACE_EMPTY_DISPLAY"])

    expect(
      ControlSurface.validateFormDefinition({
        version: 1,
        fields: [{ id: "summary", type: "display", label: "Summary", description: "Visible copy" }],
      }),
    ).toEqual([])
  })

  it("rejects manually authored expectation text", () => {
    expect(
      ControlSurface.validateFormDefinition({
        version: 1,
        fields: [],
        layout: { type: "text", text: "Erwartet: Auswahl prüfen" },
      }),
    ).toContainEqual({
      code: "SURFACE_HOST_OWNED_EXPECTATION",
      path: "form.layout.text",
      message: "Expectation text is generated by the host and must not be included in authored form content.",
    })
  })

  it("requires switchAgentAndPrompt to be the action's only step", () => {
    const diagnostics = ControlSurface.validateFormDefinition({
      version: 1,
      fields: [],
      actions: [
        {
          id: "handoff",
          trigger: { event: "click" },
          steps: [
            {
              type: "switchAgentAndPrompt",
              agent: "build",
              prompt: "Implement the approved plan",
              model: { mode: "planning-model" },
            },
            { type: "dismiss" },
          ],
        },
      ],
    })

    expect(diagnostics.map((diagnostic) => diagnostic.code)).toContain("SURFACE_MIXED_AGENT_SWITCH")
  })

  it("requires an explicit click and only one agent switch per surface", () => {
    const diagnostics = ControlSurface.validateFormDefinition({
      version: 1,
      fields: [],
      actions: [
        {
          id: "automatic-handoff",
          trigger: { event: "submit" },
          steps: [
            {
              type: "switchAgentAndPrompt",
              agent: "build",
              prompt: "Implement the approved plan",
              model: { mode: "planning-model" },
            },
          ],
        },
        {
          id: "second-handoff",
          trigger: { event: "click" },
          steps: [
            {
              type: "switchAgentAndPrompt",
              agent: "build",
              prompt: "Implement another plan",
              model: { mode: "planning-model" },
            },
          ],
        },
      ],
    })

    expect(diagnostics.map((diagnostic) => diagnostic.code)).toContain("SURFACE_AGENT_SWITCH_REQUIRES_CLICK")
    expect(diagnostics.map((diagnostic) => diagnostic.code)).toContain("SURFACE_MULTIPLE_AGENT_SWITCHES")
  })
})
