export * as ControlSurface from "./control-surface"

export type Diagnostic = {
  readonly code: string
  readonly path: string
  readonly message: string
}

export type EvaluationContext = {
  readonly values: Record<string, unknown>
  readonly state?: Record<string, Record<string, unknown>>
  readonly result?: Record<string, unknown>
  readonly fallback?: unknown
}

const removedFields = new Set(["binding", "bindings", "live", "submitActions", "rangeField", "startField", "endField"])
const styleTargets = new Set(["transform", "translateX", "translateY", "scale", "opacity", "clipPath", "borderRadius"])
const stateKeys = new Set(["currentTime", "duration", "paused"])
const expressionFunctions = new Set([
  "round",
  "clamp",
  "add",
  "sub",
  "mul",
  "div",
  "px",
  "pct",
  "concat",
  "translate",
  "translateX",
  "translateY",
  "scale",
])

export function validateFormDefinition(form: unknown) {
  return validateSurface(form, {
    root: "form",
    items: isRecord(form) && Array.isArray(form.fields) ? form.fields : [],
    effects: isRecord(form) && Array.isArray(form.effects) ? form.effects : [],
    actions: isRecord(form) && Array.isArray(form.actions) ? form.actions : [],
  })
}

export function validatePartData(part: unknown) {
  return validateSurface(part, {
    root: "controlPanel",
    items: isRecord(part) && Array.isArray(part.controls) ? part.controls : [],
    effects: isRecord(part) && Array.isArray(part.effects) ? part.effects : [],
    actions: isRecord(part) && Array.isArray(part.actions) ? part.actions : [],
  })
}

export function evaluateExpression(expression: string, context: EvaluationContext): unknown {
  const trimmed = expression.trim()
  const call = parseCall(trimmed)
  if (call && executableFunction(call.name)) return evaluateCall(call.name, call.args, context)
  const placeholder = trimmed.match(/^\$\{([^}]+)\}$/)
  if (placeholder) return readPath(placeholder[1]!.trim(), context)
  return expression.replace(/\$\{([^}]+)\}/g, (_, path) => stringifyValue(readPath(String(path).trim(), context)))
}

function validateSurface(
  input: unknown,
  surface: { root: string; items: unknown[]; effects: unknown[]; actions: unknown[] },
) {
  const diagnostics: Diagnostic[] = []
  scanRemovedFields(input, surface.root, diagnostics)
  const ids = new Set(
    surface.items
      .filter(isRecord)
      .map((item) => item.id)
      .filter((id): id is string => typeof id === "string" && id.length > 0),
  )
  const stateIds = new Set(
    surface.items
      .filter(isRecord)
      .filter((item) => item.type === "video_preview")
      .map((item) => item.id)
      .filter((id): id is string => typeof id === "string" && id.length > 0),
  )

  surface.items.forEach((item, index) => {
    if (surface.root !== "form" || !isRecord(item) || item.type !== "display") return
    const path = `${surface.root}.fields[${index}]`
    if ("value" in item || "defaultValue" in item)
      diagnostics.push({
        code: "SURFACE_LEGACY_DISPLAY_CONTENT",
        path,
        message: 'Display content belongs in "description"; "value" and "defaultValue" are legacy read-only fields.',
      })
    if (typeof item.description !== "string" || !item.description.trim())
      diagnostics.push({
        code: "SURFACE_EMPTY_DISPLAY",
        path,
        message: 'Display fields need non-empty "description" content and must not render as label-only headings.',
      })
  })
  if (surface.root === "form" && isRecord(input)) validateExpectationLayout(input.layout, "form.layout", diagnostics)

  surface.effects.forEach((effect, index) => validateEffect(effect, `${surface.root}.effects[${index}]`, ids, stateIds, diagnostics))
  const agentSwitchActions = surface.actions.filter(
    (action) =>
      isRecord(action) &&
      Array.isArray(action.steps) &&
      action.steps.some((step) => isRecord(step) && step.type === "switchAgentAndPrompt"),
  )
  if (agentSwitchActions.length > 1) {
    diagnostics.push({
      code: "SURFACE_MULTIPLE_AGENT_SWITCHES",
      path: `${surface.root}.actions`,
      message: "A surface may contain only one agent switch action.",
    })
  }
  surface.actions.forEach((action, index) => validateAction(action, `${surface.root}.actions[${index}]`, ids, stateIds, diagnostics))
  return diagnostics
}

function validateExpectationLayout(input: unknown, path: string, diagnostics: Diagnostic[]) {
  if (!isRecord(input)) return
  if (input.type === "text" && typeof input.text === "string" && /^\s*Erwartet:\s*\S/i.test(input.text))
    diagnostics.push({
      code: "SURFACE_HOST_OWNED_EXPECTATION",
      path: `${path}.text`,
      message: "Expectation text is generated by the host and must not be included in authored form content.",
    })
  if (!Array.isArray(input.children)) return
  input.children.forEach((child, index) => validateExpectationLayout(child, `${path}.children[${index}]`, diagnostics))
}

function validateEffect(effect: unknown, path: string, ids: Set<string>, stateIds: Set<string>, diagnostics: Diagnostic[]) {
  if (!isRecord(effect)) {
    diagnostics.push({ code: "SURFACE_INVALID_EFFECT", path, message: "Effect must be an object." })
    return
  }
  if (typeof effect.id !== "string" || !effect.id.trim()) {
    diagnostics.push({ code: "SURFACE_MISSING_EFFECT_ID", path, message: "Effect needs a stable id." })
  }
  if (typeof effect.target !== "string" || !validUiTarget(effect.target, ids)) {
    diagnostics.push({ code: "SURFACE_UNSUPPORTED_TARGET", path: `${path}.target`, message: `Unsupported effect target: ${String(effect.target)}` })
  }
  validateExpression(effect.value, `${path}.value`, ids, stateIds, diagnostics)
}

function validateAction(action: unknown, path: string, ids: Set<string>, stateIds: Set<string>, diagnostics: Diagnostic[]) {
  if (!isRecord(action)) {
    diagnostics.push({ code: "SURFACE_INVALID_ACTION", path, message: "Action must be an object." })
    return
  }
  if (typeof action.id !== "string" || !action.id.trim()) {
    diagnostics.push({ code: "SURFACE_MISSING_ACTION_ID", path, message: "Action needs a stable id." })
  }
  validateTrigger(action.trigger, `${path}.trigger`, ids, diagnostics)
  if (!Array.isArray(action.steps) || action.steps.length === 0) {
    diagnostics.push({ code: "SURFACE_MISSING_ACTION_STEPS", path: `${path}.steps`, message: "Action needs at least one step." })
    return
  }
  const switchSteps = action.steps.filter((step) => isRecord(step) && step.type === "switchAgentAndPrompt")
  if (switchSteps.length > 0 && (switchSteps.length !== 1 || action.steps.length !== 1)) {
    diagnostics.push({
      code: "SURFACE_MIXED_AGENT_SWITCH",
      path: `${path}.steps`,
      message: "switchAgentAndPrompt must be the action's only step.",
    })
  }
  if (switchSteps.length > 0 && (!isRecord(action.trigger) || action.trigger.event !== "click")) {
    diagnostics.push({
      code: "SURFACE_AGENT_SWITCH_REQUIRES_CLICK",
      path: `${path}.trigger.event`,
      message: "Agent switches require an explicit click trigger.",
    })
  }
  action.steps.forEach((step, index) => validateActionStep(step, `${path}.steps[${index}]`, ids, stateIds, diagnostics))
}

function validateTrigger(trigger: unknown, path: string, ids: Set<string>, diagnostics: Diagnostic[]) {
  if (!isRecord(trigger)) {
    diagnostics.push({ code: "SURFACE_INVALID_TRIGGER", path, message: "Action trigger must be an object." })
    return
  }
  if (!["change", "submit", "click", "markStart", "markEnd"].includes(String(trigger.event))) {
    diagnostics.push({ code: "SURFACE_UNSUPPORTED_TRIGGER", path: `${path}.event`, message: `Unsupported trigger event: ${String(trigger.event)}` })
  }
  if (typeof trigger.source === "string" && !ids.has(trigger.source)) {
    diagnostics.push({ code: "SURFACE_UNKNOWN_TRIGGER_SOURCE", path: `${path}.source`, message: `Unknown trigger source: ${trigger.source}` })
  }
  if (isRecord(trigger.when) && typeof trigger.when.field === "string" && !ids.has(trigger.when.field)) {
    diagnostics.push({ code: "SURFACE_UNKNOWN_WHEN_FIELD", path: `${path}.when.field`, message: `Unknown condition field: ${trigger.when.field}` })
  }
}

function validateActionStep(step: unknown, path: string, ids: Set<string>, stateIds: Set<string>, diagnostics: Diagnostic[]) {
  if (!isRecord(step)) {
    diagnostics.push({ code: "SURFACE_INVALID_ACTION_STEP", path, message: "Action step must be an object." })
    return
  }
  if (step.type === "setValue") {
    if (typeof step.target !== "string" || !validValueTarget(step.target, ids)) {
      diagnostics.push({ code: "SURFACE_UNSUPPORTED_VALUE_TARGET", path: `${path}.target`, message: `Unsupported value target: ${String(step.target)}` })
    }
    validateExpression(step.value, `${path}.value`, ids, stateIds, diagnostics)
    return
  }
  if (step.type === "configWrite") {
    if (!isRecord(step.target) || typeof step.target.path !== "string" || typeof step.target.format !== "string") {
      diagnostics.push({ code: "SURFACE_INVALID_CONFIG_TARGET", path: `${path}.target`, message: "Config action needs target.path and target.format." })
    }
    if (typeof step.value === "string") validateExpression(step.value, `${path}.value`, ids, stateIds, diagnostics)
    return
  }
  if (step.type === "livePublish") {
    if (typeof step.value === "string") validateExpression(step.value, `${path}.value`, ids, stateIds, diagnostics)
    return
  }
  if (step.type === "switchAgentAndPrompt") {
    if (typeof step.agent !== "string" || !step.agent.trim())
      diagnostics.push({ code: "SURFACE_INVALID_AGENT", path: `${path}.agent`, message: "Agent must be non-empty." })
    if (typeof step.prompt !== "string" || !step.prompt.trim())
      diagnostics.push({ code: "SURFACE_INVALID_PROMPT", path: `${path}.prompt`, message: "Prompt must be non-empty." })
    if (!isRecord(step.model) || !["planning-model", "implementation-model"].includes(String(step.model.mode))) {
      diagnostics.push({ code: "SURFACE_INVALID_MODEL", path: `${path}.model`, message: "Model selection is invalid." })
    } else if (
      step.model.mode === "implementation-model" &&
      (typeof step.model.ref !== "string" || !step.model.ref.trim())
    ) {
      diagnostics.push({ code: "SURFACE_INVALID_MODEL", path: `${path}.model.ref`, message: "Implementation model ref must be non-empty." })
    }
    return
  }
  if (step.type === "command" || step.type === "gmail" || step.type === "dismiss") return
  diagnostics.push({ code: "SURFACE_UNSUPPORTED_ACTION_STEP", path: `${path}.type`, message: `Unsupported action step type: ${String(step.type)}` })
}

function validateExpression(value: unknown, path: string, ids: Set<string>, stateIds: Set<string>, diagnostics: Diagnostic[]) {
  if (typeof value !== "string") {
    diagnostics.push({ code: "SURFACE_INVALID_EXPRESSION", path, message: "Expression must be a string." })
    return
  }
  for (const name of value.matchAll(/\b([a-zA-Z][a-zA-Z0-9_]*)\s*\(/g)) {
    if (!expressionFunctions.has(name[1]!)) {
      diagnostics.push({ code: "SURFACE_UNSUPPORTED_FUNCTION", path, message: `Unsupported expression function: ${name[1]}` })
    }
  }
  for (const ref of value.matchAll(/\$\{([^}]+)\}/g)) {
    validateReference(ref[1]!.trim(), path, ids, stateIds, diagnostics)
  }
}

function validateReference(ref: string, path: string, ids: Set<string>, stateIds: Set<string>, diagnostics: Diagnostic[]) {
  const value = ref.match(/^values\.([A-Za-z0-9_-]+)(?:\.(start|end))?$/)
  if (value) {
    if (!ids.has(value[1]!)) diagnostics.push({ code: "SURFACE_UNKNOWN_VALUE", path, message: `Unknown value id: ${value[1]}` })
    return
  }
  const state = ref.match(/^state\.([A-Za-z0-9_-]+)\.([A-Za-z0-9_-]+)$/)
  if (state) {
    if (!stateIds.has(state[1]!)) diagnostics.push({ code: "SURFACE_UNKNOWN_STATE", path, message: `Unknown state id: ${state[1]}` })
    if (!stateKeys.has(state[2]!)) diagnostics.push({ code: "SURFACE_UNKNOWN_STATE_KEY", path, message: `Unsupported state key: ${state[2]}` })
    return
  }
  if (/^result\.(ok|exitCode|stdout|stderr|output)$/.test(ref)) return
  if (/^result\.json\.[A-Za-z0-9_-]+$/.test(ref)) return
  diagnostics.push({ code: "SURFACE_UNSUPPORTED_REFERENCE", path, message: `Unsupported reference: ${ref}` })
}

function validUiTarget(target: string, ids: Set<string>) {
  const src = target.match(/^ui\.([A-Za-z0-9_-]+)\.(src|poster)$/)
  if (src) return ids.has(src[1]!)
  const media = target.match(/^ui\.([A-Za-z0-9_-]+)\.media\.currentTime$/)
  if (media) return ids.has(media[1]!)
  const style = target.match(/^ui\.([A-Za-z0-9_-]+)\.style\.([A-Za-z0-9_-]+)$/)
  if (style) return ids.has(style[1]!) && styleTargets.has(style[2]!)
  return false
}

function validValueTarget(target: string, ids: Set<string>) {
  const match = target.match(/^values\.([A-Za-z0-9_-]+)(?:\.(start|end))?$/)
  return !!match && ids.has(match[1]!)
}

function scanRemovedFields(value: unknown, path: string, diagnostics: Diagnostic[]) {
  if (Array.isArray(value)) {
    value.forEach((item, index) => scanRemovedFields(item, `${path}[${index}]`, diagnostics))
    return
  }
  if (!isRecord(value)) return
  for (const [key, nested] of Object.entries(value)) {
    if (removedFields.has(key)) {
      diagnostics.push({ code: "SURFACE_REMOVED_FIELD", path: `${path}.${key}`, message: `Removed UI field '${key}' must be migrated to effects/actions.` })
    }
    scanRemovedFields(nested, `${path}.${key}`, diagnostics)
  }
}

function parseCall(value: string) {
  const match = value.match(/^([a-zA-Z][a-zA-Z0-9_]*)\((.*)\)$/)
  if (!match) return
  return { name: match[1]!, args: splitArgs(match[2]!) }
}

function executableFunction(name: string) {
  return ["round", "clamp", "add", "sub", "mul", "div", "px", "pct", "concat"].includes(name)
}

function evaluateCall(name: string, args: string[], context: EvaluationContext): unknown {
  const values = args.map((arg) => evaluateArg(arg, context))
  if (name === "concat") return values.map(stringifyValue).join("")
  const numbers = values.map(numberValue)
  if (name === "round") return Number((numbers[0] ?? 0).toFixed(Math.max(0, numbers[1] ?? 0)))
  if (name === "clamp") return Math.min(numbers[2] ?? Number.POSITIVE_INFINITY, Math.max(numbers[1] ?? Number.NEGATIVE_INFINITY, numbers[0] ?? 0))
  if (name === "add") return (numbers[0] ?? 0) + (numbers[1] ?? 0)
  if (name === "sub") return (numbers[0] ?? 0) - (numbers[1] ?? 0)
  if (name === "mul") return (numbers[0] ?? 0) * (numbers[1] ?? 0)
  if (name === "div") return (numbers[0] ?? 0) / (numbers[1] || 1)
  if (name === "px") return `${numbers[0] ?? 0}px`
  return `${numbers[0] ?? 0}%`
}

function evaluateArg(arg: string, context: EvaluationContext): unknown {
  const trimmed = arg.trim()
  const placeholder = trimmed.match(/^\$\{([^}]+)\}$/)
  if (placeholder) return readPath(placeholder[1]!.trim(), context)
  const nested = parseCall(trimmed)
  if (nested && executableFunction(nested.name)) return evaluateCall(nested.name, nested.args, context)
  const number = Number(trimmed)
  if (Number.isFinite(number)) return number
  return trimmed.replace(/^['"]|['"]$/g, "")
}

function readPath(path: string, context: EvaluationContext): unknown {
  const value = path.match(/^values\.([A-Za-z0-9_-]+)(?:\.(start|end))?$/)
  if (value) {
    const item = context.values[value[1]!]
    if (!value[2]) return item ?? context.fallback
    return isRecord(item) ? item[value[2]!] ?? context.fallback : context.fallback
  }
  const state = path.match(/^state\.([A-Za-z0-9_-]+)\.([A-Za-z0-9_-]+)$/)
  if (state) return context.state?.[state[1]!]?.[state[2]!] ?? context.fallback
  const result = path.match(/^result\.(ok|exitCode|stdout|stderr|output)$/)
  if (result) return context.result?.[result[1]!] ?? context.fallback
  const resultJson = path.match(/^result\.json\.([A-Za-z0-9_-]+)$/)
  if (resultJson) {
    const json = context.result?.json
    return isRecord(json) ? json[resultJson[1]!] ?? context.fallback : context.fallback
  }
  return context.fallback
}

function splitArgs(value: string) {
  const args: string[] = []
  let depth = 0
  let start = 0
  for (let index = 0; index < value.length; index++) {
    const char = value[index]
    if (char === "(") depth++
    if (char === ")") depth--
    if (char === "," && depth === 0) {
      args.push(value.slice(start, index))
      start = index + 1
    }
  }
  args.push(value.slice(start))
  return args.filter((arg) => arg.trim().length > 0)
}

function stringifyValue(value: unknown) {
  if (value === undefined || value === null) return ""
  if (typeof value === "string") return value
  if (typeof value === "number" || typeof value === "boolean") return String(value)
  return JSON.stringify(value)
}

function numberValue(value: unknown) {
  const number = typeof value === "number" ? value : Number(value)
  return Number.isFinite(number) ? number : undefined
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value)
}
